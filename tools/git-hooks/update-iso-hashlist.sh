#!/usr/bin/env bash
# Regenerates data/iso_file_hashes.sha256: SHA-256 of every file on the reference
# CD data track plus the CD images themselves. The pre-commit guard refuses any
# staged file whose content matches one of these hashes. Hashes only; no game data.
set -euo pipefail
# The CD image lies in the dependency directory's archive/, its extraction in the
# main checkout's ignored build/extracted. The list keeps the paths relative to those two roots.
repo_root="$(cd "$(dirname "$0")/../.." && pwd)"
main_root="$(dirname "$(git -C "$repo_root" rev-parse --path-format=absolute --git-common-dir)")"
build_root="${ES2_BUILD_ROOT:-$main_root/build}"
deps_root="${ES2_DEPENDENCIES:-$(dirname "$main_root")/es2-dependencies}"
image=archive/EarthSiege2_Freeware_GoldGames_1r11_withAudio.iso
out="$repo_root/data/iso_file_hashes.sha256"
[ -f "$deps_root/$image" ] || { echo "missing $deps_root/$image" >&2; exit 1; }
cd "$build_root"
[ -d extracted/cd ] || { echo "missing $build_root/extracted/cd" >&2; exit 1; }
tmp="$(mktemp)"
{
  echo "# SHA-256 of files that originate directly from the EarthSiege II reference CD."
  echo "# Generated by tools/git-hooks/update-iso-hashlist.sh; consumed by tools/git-hooks/pre-commit."
  echo "# Empty files are omitted. Paths: archive/ below the dependency directory, extracted/ below the checkout's build/."
  {
    (cd "$deps_root" && sha256sum "$image")
    sha256sum extracted/earthsiege2-data.iso
    find extracted/cd -type f -size +0c -print0 | sort -z | xargs -0 sha256sum
  } | awk '{ h = tolower($1); sub(/^\\/, "", h); p = $0; sub(/^[^ ]+ [ *]/, "", p); print h "  " p }'
  echo "# Members of the VOLN archives (layout: docs/formats/vol.md), as 'vol:<archive>:<dir><name>'."
  find extracted/cd -type f -iname '*.vol' -print0 | sort -z | xargs -0 perl -MDigest::SHA=sha256_hex -e '
    for my $path (@ARGV) {
      open(my $fh, "<:raw", $path) or die "$path: $!";
      local $/; my $b = <$fh>; close($fh);
      next unless substr($b, 0, 4) eq "VOLN";
      my $ndirs = unpack("C", substr($b, 9, 1));
      my $d = unpack("v", substr($b, 10, 2));
      my @dirs = (split(/\0/, substr($b, 12, $d), -1))[0 .. $ndirs - 1];
      my ($n, $tlen) = unpack("vV", substr($b, 12 + $d, 6));
      die "$path: bad member table" unless $tlen == 18 * $n;
      for my $i (0 .. $n - 1) {
        my $r = 18 + $d + 18 * $i;
        my ($name) = split(/\0/, substr($b, $r, 13));
        my ($dir, $off) = unpack("CV", substr($b, $r + 13, 5));
        my ($kind, $len) = unpack("CV", substr($b, $off, 5));
        die "$path: member $name kind $kind" unless $kind == 2;
        die "$path: member $name out of bounds" if $off + 10 + $len > length($b);
        print sha256_hex(substr($b, $off + 9, $len)), "  vol:$path:$dirs[$dir]$name\n";
      }
    }' | sed 's#vol:extracted/cd/#vol:#'
} > "$tmp"
mv "$tmp" "$out"
echo "wrote $(grep -vc '^#' "$out") hashes to $out"
