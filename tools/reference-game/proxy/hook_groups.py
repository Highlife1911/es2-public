"""Derive per-group #include lists from the hook registry (build step).

The registry (hook_registry.h) names every hook's descriptor array and its
adapter group, in a fixed order. Two header lists follow from it:

  adapters  for each group, in order of its first registry entry, the
            *_hooks.h file that defines the group's descriptor array
            (rng_hooks.h, the includer, is skipped).
  cases     for each group, the *_cases.h file that defines
            "static int <group>_cases(unsigned index,unsigned limit)" or
            "#define <group>_cases ..." (legacy_cases.h for the first groups).

Each header appears once, at the position of the first group that needs it,
so every header still sees all headers of earlier groups. The output is a
generated header of #include lines; nothing is written to the source tree.
"""
import argparse
from pathlib import Path
import re

REGISTRY = re.compile(r"^ES2_HOOK\((\w+),\s*(0x[0-9a-fA-F]+),\s*(\w+)\[(\d+)\],\s*([^,]+),\s*(\w+)\)\s*$", re.M)
DESCRIPTOR_ARRAY = re.compile(r"\bes2_hook_descriptor\s+(\w+)\s*\[\s*\]\s*=")
CASES_FUNCTION = re.compile(r"^(?:static\s+int\s+(\w+)_cases\s*\(\s*unsigned\s+\w+\s*,\s*unsigned\s+\w+\s*\)|#define\s+(\w+)_cases\b)", re.M)


def groups(registry_text):
    """Return [(group, descriptor array)] in order of first appearance."""
    rows = REGISTRY.findall(registry_text)
    if not rows:
        raise ValueError("no ES2_HOOK entries in the registry")
    result, seen = [], {}
    for _, _, array, _, _, group in rows:
        if group in seen:
            if seen[group] != array:
                # One group may own one descriptor array only; the C side
                # relies on that for the per-group dispatch.
                raise ValueError(f"group {group} uses two descriptor arrays: {seen[group]}, {array}")
            continue
        seen[group] = array
        result.append((group, array))
    return result


def owners(headers, pattern):
    """Map each symbol found by pattern to the one header defining it."""
    found = {}
    for header in headers:
        for match in pattern.finditer(header.read_text(encoding="utf-8")):
            symbol = next(group for group in match.groups() if group)
            if symbol in found and found[symbol] != header:
                raise ValueError(f"{symbol} is defined in {found[symbol].name} and {header.name}")
            found[symbol] = header
    return found


def includes(kind, registry_text, headers, exclude):
    pattern = DESCRIPTOR_ARRAY if kind == "adapters" else CASES_FUNCTION
    table = owners(headers, pattern)
    ordered = []
    for group, array in groups(registry_text):
        key = array if kind == "adapters" else group
        if key not in table:
            what = f"descriptor array {array}" if kind == "adapters" else f"{group}_cases"
            raise ValueError(f"group {group}: no header defines {what}")
        header = table[key]
        if header.name not in exclude and header not in ordered:
            ordered.append(header)
    return ordered


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--kind", choices=["adapters", "cases"], required=True)
    parser.add_argument("--registry", type=Path, required=True)
    parser.add_argument("--prefix", required=True, help="workspace-relative include directory")
    parser.add_argument("--exclude", action="append", default=[], help="header base name to skip")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("headers", type=Path, nargs="+")
    args = parser.parse_args()
    ordered = includes(args.kind, args.registry.read_text(encoding="utf-8"), args.headers, set(args.exclude))
    lines = [f"/* Generated by tools/reference-game/proxy/hook_groups.py --kind {args.kind}",
             " * from hook_registry.h (group order of first registration). Do not edit. */"]
    lines += [f'#include "{args.prefix}/{header.name}"' for header in ordered]
    args.out.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))


if __name__ == "__main__":
    main()
