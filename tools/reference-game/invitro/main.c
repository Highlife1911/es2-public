/* The hook-group harness: every registered hook of the registry against its
 * own-code replacement, the CW3220 runtime cases and the probes. The sim suites
 * run in their own binaries (sim_main.c, suites.bzl). */
#define ES2_INVITRO_HOOKS
#include "harness_base.h"
static uint32_t original_edx;
static uint32_t original(unsigned index,const uint32_t *a) {
    es2_hook_result r; es2_hook_call call={mapped+function_hook_descriptor(index)->rva,ES2_ABI_CDECL,
        function_hook_descriptor(index)->arg_count,a,initial_fpu,&r,NULL};
    es2_hook_machine_call(&call);
    if(get16(r.fpu)!=get16(initial_fpu) || get16(r.fpu+4)!=get16(initial_fpu+4) || get16(r.fpu+8)!=get16(initial_fpu+8)) {
        fprintf(stderr,"FAIL: %s changed x87 CW/SW/tags\n",current_function); longjmp(trap_return,1);
    }
    original_edx=r.edx;return r.eax;
}
