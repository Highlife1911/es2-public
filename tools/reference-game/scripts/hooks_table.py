#!/usr/bin/env python3
"""The registry table of docs/reference-game/hooks.md, generated.

One row per hook of tools/reference-game/proxy/hook_registry.h, in registry
order: name, VA (image base 0x400000 plus the registry RVA), registry group,
whether it accepts `compare` (the hooks before `euler_matrix` always do; from
`euler_matrix` on a hook does exactly when hooks.md carries its diagnostic
`-Hooks "<name>=compare"` line, which hook_registry_test checks against the
descriptors), and the live counts of docs/reference-game/hook_live_counts.json
(calls in c1_01-success, number of suites with a call, calls over all suites).

  python -B hooks_table.py render  [--hooks-md P] [--registry P] [--counts P] (--check | --write)
  python -B hooks_table.py counts  --output P (--compared FILE | --flat FILE)... [--source TEXT]

`render --check` exits 1 when the table between the two markers differs from
the generated one (the Bazel test); `--write` rewrites it in place. `counts`
builds the counts file from hook-counters.json files of all-replaced runs:
`--compared` reads the `compared_tick` view (tools/check.ps1, run-oracle-parallel),
`--flat` the `counters` view of the session's flat-run extractor; a suite named
twice keeps the last file. Standard library only; LF output.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
BEGIN = '<!-- hooks table: generated by tools/reference-game/scripts/hooks_table.py from hook_registry.h, the compare lines below and hook_live_counts.json; do not edit -->'
END = '<!-- end of the generated hooks table -->'
FIRST_DESCRIBED = 'euler_matrix'
HEADER = ['| Hook | VA | Group | Compare | c1_01-success calls | Suites with calls | Calls, all suites |',
          '| --- | --- | --- | --- | ---: | ---: | ---: |']
HOOK_LINE = re.compile(r'^ES2_HOOK\((\w+),\s*0x([0-9A-Fa-f]+),\s*[^,]+,\s*[^,]+,\s*(\w+)\)\s*$')
COMPARE_LINE = re.compile(r'^-Hooks "([a-z0-9_]+)=compare"$')
CALLS = re.compile(r'^hk_([a-z0-9_]+)_calls$')


def registry(path):
    hooks = []
    for line in Path(path).read_text(encoding='utf-8').splitlines():
        m = HOOK_LINE.match(line.strip())
        if m:
            hooks.append((m.group(1), 0x400000 + int(m.group(2), 16), m.group(3)))
    if not hooks:
        raise ValueError(f'no ES2_HOOK lines in {path}')
    names = [h[0] for h in hooks]
    if len(set(names)) != len(names):
        raise ValueError('duplicate hook names in the registry')
    return hooks


def compare_set(hooks, text):
    names = [h[0] for h in hooks]
    if FIRST_DESCRIBED not in names:
        raise ValueError(f'{FIRST_DESCRIBED} is not in the registry')
    lines = {m.group(1) for line in text.splitlines() for m in [COMPARE_LINE.match(line)] if m}
    unknown = lines - set(names)
    if unknown:
        raise ValueError(f'compare lines for unknown hooks: {sorted(unknown)}')
    first = names.index(FIRST_DESCRIBED)
    return set(names[:first]) | lines


def number(n):
    return f'{n:,}'


def render_rows(hooks, compare, counts):
    data = counts.get('hooks', {})
    rows = list(HEADER)
    for name, va, group in hooks:
        c = data.get(name)
        cells = (number(c[0]), str(c[1]), number(c[2])) if c else ('–', '–', '–')
        rows.append(f'| `{name}` | {va:06x} | {group} | {"yes" if name in compare else "no"} | ' + ' | '.join(cells) + ' |')
    note = (f'Live counts: {counts.get("source", "none")}; {counts.get("suite_count", 0)} suites. '
            '"–" means the hook has no counter in that source.')
    return rows + ['', note]


def split_doc(text):
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise ValueError('hooks.md needs exactly one begin and one end marker of the generated table')
    head, rest = text.split(BEGIN + '\n', 1)
    body, tail = rest.split(END, 1)
    return head, body, tail


def render(args):
    doc = Path(args.hooks_md).read_text(encoding='utf-8')
    hooks = registry(args.registry)
    counts = json.loads(Path(args.counts).read_text(encoding='utf-8'))
    table = '\n'.join(render_rows(hooks, compare_set(hooks, doc), counts)) + '\n'
    head, body, tail = split_doc(doc)
    if args.check:
        if body != table:
            old, new = body.splitlines(), table.splitlines()
            first = next((i for i, (a, b) in enumerate(zip(old, new)) if a != b), min(len(old), len(new)))
            print(f'hooks.md: the generated table differs from line {first + 1} of the table '
                  f'(run hooks_table.py render --write): {old[first] if first < len(old) else "<end>"!r} '
                  f'-> {new[first] if first < len(new) else "<end>"!r}')
            return 1
        print(f'OK: hooks.md table matches {len(hooks)} registry hooks')
        return 0
    Path(args.hooks_md).write_bytes((head + BEGIN + '\n' + table + END + tail).encode('utf-8'))
    print(f'wrote {len(hooks)} rows to {args.hooks_md}')
    return 0


def counts(args):
    suites = {}
    for kind, path in args.inputs:
        j = json.loads(Path(path).read_text(encoding='utf-8'))
        for suite, entry in j['suites'].items():
            view = entry['compared_tick'] if kind == 'compared' else entry['counters']
            suites[suite] = {m.group(1): v for k, v in view.items() for m in [CALLS.match(k)] if m}
    if not suites:
        raise ValueError('no suites in the inputs')
    names = sorted({h for s in suites.values() for h in s})
    hooks = {}
    for h in names:
        values = [s.get(h, 0) for s in suites.values()]
        hooks[h] = [suites.get('c1_01-success', {}).get(h, 0), sum(1 for v in values if v), sum(values)]
    out = dict(source=args.source or ', '.join(Path(p).parent.name for _, p in args.inputs),
               suite_count=len(suites), suites=sorted(suites), hooks=hooks)
    Path(args.output).write_bytes((json.dumps(out, indent=1, sort_keys=True) + '\n').encode('utf-8'))
    print(f'wrote {len(hooks)} hooks over {len(suites)} suites to {args.output}')
    return 0


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest='command', required=True)
    r = sub.add_parser('render')
    r.add_argument('--hooks-md', default=str(ROOT / 'docs/reference-game/hooks.md'))
    r.add_argument('--registry', default=str(ROOT / 'tools/reference-game/proxy/hook_registry.h'))
    r.add_argument('--counts', default=str(ROOT / 'docs/reference-game/hook_live_counts.json'))
    mode = r.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--write', action='store_true')
    c = sub.add_parser('counts')
    c.add_argument('--output', required=True)
    c.add_argument('--compared', action='append', default=[], metavar='FILE')
    c.add_argument('--flat', action='append', default=[], metavar='FILE')
    c.add_argument('--source', default='')
    args = p.parse_args(argv)
    try:
        if args.command == 'render':
            return render(args)
        args.inputs = [('compared', f) for f in args.compared] + [('flat', f) for f in args.flat]
        return counts(args)
    except (ValueError, KeyError, OSError) as error:
        print(f'hooks_table: {error}', file=sys.stderr)
        return 2


if __name__ == '__main__':
    sys.exit(main())
