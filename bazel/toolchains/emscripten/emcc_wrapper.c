/* Runs one Emscripten driver script (ES2_TOOL: emcc, em++ or emar) with the SDK's own Python and the environment
   the pinned, frozen SDK needs; built once per tool by bazel/toolchains/emscripten/BUILD.bazel.

   A link whose output ends in ".wasm" produces one file: emcc writes <base>.js, <base>.wasm and whatever else a
   link emits into a scratch directory, and the files are packed into the output (format in wasm_bundle.h).
   wasm_unpack.exe restores them, so the link stays a single-output action for Bazel. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <windows.h>
#include "wasm_bundle.h"
/* ES2_TOOL, ES2_EMSDK_ROOT, ES2_EMSDK_PYTHON and ES2_EMSDK_NODE as string literals, generated by the BUILD file. */
#include <wrapper_config.h>

typedef struct { char *data; size_t length, capacity; } buffer;

static void fail(const char *what, const char *detail) {
    fprintf(stderr, "emcc_wrapper: %s: %s\n", what, detail);
    exit(2);
}

static void put(buffer *b, const char *text, size_t n) {
    if (b->length + n + 1 > b->capacity) {
        b->capacity = (b->length + n + 1) * 2;
        b->data = (char *)realloc(b->data, b->capacity);
        if (!b->data) fail("out of memory", "command line");
    }
    memcpy(b->data + b->length, text, n);
    b->length += n;
    b->data[b->length] = 0;
}

/* One argument in the CommandLineToArgvW convention. */
static void put_argument(buffer *b, const char *arg) {
    const char *p;
    size_t backslashes = 0;
    if (b->length) put(b, " ", 1);
    put(b, "\"", 1);
    for (p = arg; *p; p++) {
        if (*p == '\\') { backslashes++; continue; }
        if (*p == '"') for (; backslashes; backslashes--) put(b, "\\", 1), put(b, "\\", 1);
        else for (; backslashes; backslashes--) put(b, "\\", 1);
        if (*p == '"') put(b, "\\", 1);
        put(b, p, 1);
    }
    for (; backslashes; backslashes--) put(b, "\\\\", 2);
    put(b, "\"", 1);
}

static void set_environment(const char *name, const char *value) {
    if (!SetEnvironmentVariableA(name, value)) fail("cannot set", name);
}

static int run(char *command_line) {
    STARTUPINFOA startup;
    PROCESS_INFORMATION process;
    DWORD code;
    memset(&startup, 0, sizeof startup);
    startup.cb = sizeof startup;
    startup.dwFlags = STARTF_USESTDHANDLES;
    startup.hStdInput = GetStdHandle(STD_INPUT_HANDLE);
    startup.hStdOutput = GetStdHandle(STD_OUTPUT_HANDLE);
    startup.hStdError = GetStdHandle(STD_ERROR_HANDLE);
    if (!CreateProcessA(NULL, command_line, NULL, NULL, TRUE, CREATE_NO_WINDOW, NULL, NULL, &startup, &process))
        fail("cannot start", command_line);
    WaitForSingleObject(process.hProcess, INFINITE);
    if (!GetExitCodeProcess(process.hProcess, &code)) code = 2;
    CloseHandle(process.hProcess);
    CloseHandle(process.hThread);
    return (int)code;
}

static int ends_with(const char *text, const char *suffix) {
    size_t n = strlen(text), m = strlen(suffix);
    return n >= m && strcmp(text + n - m, suffix) == 0;
}

static void remove_tree(const char *directory) {
    char pattern[MAX_PATH], path[MAX_PATH];
    WIN32_FIND_DATAA entry;
    HANDLE find;
    if (snprintf(pattern, sizeof pattern, "%s\\*", directory) >= (int)sizeof pattern) fail("path too long", directory);
    find = FindFirstFileA(pattern, &entry);
    if (find != INVALID_HANDLE_VALUE) {
        do {
            if (!strcmp(entry.cFileName, ".") || !strcmp(entry.cFileName, "..")) continue;
            if (snprintf(path, sizeof path, "%s\\%s", directory, entry.cFileName) >= (int)sizeof path) fail("path too long", directory);
            if (entry.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY) remove_tree(path);
            else DeleteFileA(path);
        } while (FindNextFileA(find, &entry));
        FindClose(find);
    }
    RemoveDirectoryA(directory);
}

static int compare_names(const void *a, const void *b) { return strcmp(*(char *const *)a, *(char *const *)b); }

/* Packs the regular files of `directory` into `output`, sorted by name. */
static void pack(const char *directory, const char *output) {
    char pattern[MAX_PATH], path[MAX_PATH], *names[256];
    unsigned count = 0, i;
    WIN32_FIND_DATAA entry;
    HANDLE find;
    FILE *out;
    if (snprintf(pattern, sizeof pattern, "%s\\*", directory) >= (int)sizeof pattern) fail("path too long", directory);
    find = FindFirstFileA(pattern, &entry);
    if (find == INVALID_HANDLE_VALUE) fail("no link output in", directory);
    do {
        if (entry.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY) continue;
        if (count == 256) fail("too many link outputs in", directory);
        names[count++] = _strdup(entry.cFileName);
    } while (FindNextFileA(find, &entry));
    FindClose(find);
    if (!count) fail("no link output in", directory);
    qsort(names, count, sizeof names[0], compare_names);
    out = fopen(output, "wb");
    if (!out) fail("cannot write", output);
    if (!wasm_bundle_begin(out)) fail("cannot write", output);
    for (i = 0; i < count; i++) {
        FILE *in;
        char *data;
        long size = -1;
        snprintf(path, sizeof path, "%s\\%s", directory, names[i]);
        in = fopen(path, "rb");
        if (in && !fseek(in, 0, SEEK_END)) size = ftell(in);
        if (size < 0 || fseek(in, 0, SEEK_SET)) fail("cannot read", path);
        data = (char *)malloc((size_t)size + 1);
        if (!data || fread(data, 1, (size_t)size, in) != (size_t)size) fail("cannot read", path);
        fclose(in);
        if (!wasm_bundle_add(out, names[i], data, (size_t)size)) fail("cannot write", output);
        free(data);
    }
    if (fclose(out)) fail("cannot write", output);
}

int main(int argc, char **argv) {
    const char *root = ES2_EMSDK_ROOT;
    char python[MAX_PATH], script[MAX_PATH], path[MAX_PATH], scratch[MAX_PATH], scratch_output[MAX_PATH];
    buffer line = {0};
    const char *bundle = NULL, *base_start = NULL;
    int i, code, bundle_index = -1;
    size_t base_length = 0;

    snprintf(python, sizeof python, "%s", ES2_EMSDK_PYTHON);
    snprintf(script, sizeof script, "%s/upstream/emscripten/" ES2_TOOL ".py", root);
    /* The pinned SDK as emsdk_env would set it, with the prebuilt system libraries frozen: no cache write, no build. */
    snprintf(path, sizeof path, "%s/.emscripten", root);
    set_environment("EM_CONFIG", path);
    set_environment("EMSDK", root);
    set_environment("EMSDK_PYTHON", python);
    set_environment("EMSDK_NODE", ES2_EMSDK_NODE);
    set_environment("EM_FROZEN_CACHE", "1");
    set_environment("PYTHONDONTWRITEBYTECODE", "1");

    for (i = 1; i + 1 < argc; i++) {
        if (strcmp(argv[i], "-o") == 0 && ends_with(argv[i + 1], WASM_BUNDLE_EXTENSION)) {
            const char *name = argv[i + 1], *slash, *p;
            for (slash = p = name; *p; p++) if (*p == '/' || *p == '\\') slash = p + 1;
            bundle = name;
            bundle_index = i + 1;
            base_start = slash;
            base_length = strlen(slash) - strlen(WASM_BUNDLE_EXTENSION);
        }
    }
    if (bundle) {
        if (snprintf(scratch, sizeof scratch, "%s.dir", bundle) >= (int)sizeof scratch ||
            snprintf(scratch_output, sizeof scratch_output, "%s.dir/%.*s.js", bundle, (int)base_length, base_start) >= (int)sizeof scratch_output)
            fail("path too long", bundle);
        remove_tree(scratch);
        if (!CreateDirectoryA(scratch, NULL)) fail("cannot create", scratch);
    }

    /* -B -E -s: no bytecode written into the SDK, no PYTHON* variables, no user site. */
    put_argument(&line, python);
    put_argument(&line, "-B");
    put_argument(&line, "-E");
    put_argument(&line, "-s");
    put_argument(&line, script);
    for (i = 1; i < argc; i++) put_argument(&line, i == bundle_index ? scratch_output : argv[i]);
    code = run(line.data);
    if (bundle) {
        if (code == 0) pack(scratch, bundle);
        remove_tree(scratch);
    }
    return code;
}
